/// Minimal cancellation primitive so the binary does not pull in tokio-util for one type.
mod tokio_util_shim {
    use std::sync::atomic::{AtomicBool, Ordering};
    use std::sync::Arc;

    #[derive(Clone, Default)]
    pub struct CancellationToken(Arc<AtomicBool>);

    impl CancellationToken {
        pub fn new() -> Self {
            Self::default()
        }
        pub fn cancel(&self) {
            self.0.store(true, Ordering::SeqCst);
        }
        pub fn is_cancelled(&self) -> bool {
            self.0.load(Ordering::SeqCst)
        }
    }
}

#[derive(Parser)]
#[command(name = "ddi", version, about, long_about = None)]
struct Cli {
    /// Path to the pipeline config (TOML).
    #[arg(
        short,
        long,
        global = true,
        env = "DDI_CONFIG",
        default_value = "pipelines.toml"
    )]
    config: PathBuf,

    /// Prometheus metrics listen address. Omit to disable.
    #[arg(long, global = true, env = "DDI_METRICS_ADDR")]
    metrics_addr: Option<String>,

    /// Run only these pipelines, by name. Repeatable. Names match dbt model names when
    /// the config was generated by `ddi dbt convert`.
    #[arg(short = 's', long = "select", global = true, value_name = "NAME")]
    select: Vec<String>,

    /// dbt target to take warehouse credentials from, as `dbt --target` does.
    ///
    /// With this set, table locations are resolved from the catalog rather than guessed
    /// from the manifest, and re-resolved on every poll so a table that moves is followed.
    #[arg(
        short = 't',
        long,
        global = true,
        value_name = "TARGET",
        env = "DDI_TARGET"
    )]
    target: Option<String>,

    /// dbt profile to use. Defaults to the only one in the file.
    #[arg(long, global = true, value_name = "NAME")]
    profile: Option<String>,

    /// Directory holding profiles.yml. Defaults to $DBT_PROFILES_DIR, ./, then ~/.dbt.
    #[arg(long, global = true, value_name = "DIR", env = "DBT_PROFILES_DIR")]
    profiles_dir: Option<PathBuf>,

    #[command(subcommand)]
    command: Option<Command>,
}

#[derive(Subcommand)]
enum Command {
    /// Validate the config and exit. Nothing is read or written.
    Validate,
    /// Run every pipeline until each is caught up, then exit.
    Once,
    /// Run continuously (the default).
    Run,
    /// Print each pipeline's resume point and how far behind it is.
    Status,
    /// Work with a dbt project.
    #[command(subcommand)]
    Dbt(DbtCommand),
}

#[derive(Subcommand)]
enum DbtCommand {
    /// Classify every model in a dbt manifest as streamable or not, with reasons.
    Check {
        /// Path to target/manifest.json. Defaults to [dbt].manifest in the config.
        #[arg(long)]
        manifest: Option<PathBuf>,
        /// Show only the models that cannot be streamed.
        #[arg(long)]
        rejected_only: bool,
    },
    /// Emit a pipelines.toml for every streamable model.
    Convert {
        #[arg(long)]
        manifest: Option<PathBuf>,
        /// Write here instead of stdout.
        #[arg(long)]
        out: Option<PathBuf>,
    },
}

/// Default log filter: our own events at info, and the storage stack quiet.
///
/// `buoyant_kernel` is delta-rs's Delta-kernel implementation, and it logs a full snapshot
/// dump per commit at info. Leaving it out of this filter buries every line the daemon
/// actually emits.
const DEFAULT_LOG: &str =
    "info,deltalake=warn,deltalake_core=warn,buoyant_kernel=warn,datafusion=warn";

#[tokio::main]
async fn main() -> std::process::ExitCode {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| DEFAULT_LOG.into()),
        )
        .init();

    let cli = Cli::parse();
    match run(cli).await {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(e) => {
            error!("{e}");
            std::process::ExitCode::FAILURE
        }
    }
}

async fn run(cli: Cli) -> delta_delta_ingest::Result<()> {
    let cfg = Config::from_path(&cli.config)?;

    // The dbt subcommands read a manifest, not the pipeline list, so they must work
    // before any pipelines exist — that is the point at which you are deciding what to
    // put in the config.
    if let Some(Command::Dbt(sub)) = &cli.command {
        return dbt_command(sub, &cfg, &cli).await;
    }

    // Partial by design: one unusable entry in a config of three hundred must not keep the
    // other two hundred and ninety-nine off the air. What cannot run is named, counted and
    // exported; what can, runs.
    let resolved = cfg.resolve_all()?;
    let rejected = resolved.rejected;
    let pipelines = select(resolved.pipelines, &cli.select, &rejected)?;

    // With a dbt target named, the catalog is the authority on where tables live.
    let locator = Arc::new(build_locator(&cli)?);
    for r in &rejected {
        error!(pipeline = %r.name, "held back: {}", r.reason);
    }
    // Divided by what will actually run, not by what was written down: a held-back pipeline
    // allocates nothing, and counting it would make everyone else's share too small.
    let budget = cfg.budget(pipelines.len())?;
    budget.clone().install();

    // The count limit and the memory limit answer different questions and are deliberately
    // not derived from one another: the budget bounds what one pipeline holds, the gate
    // bounds how many of them are reading a target at the same instant. See `crate::gate`.
    gate::install(gate::Gate::new(
        cfg.runtime.max_concurrent_upsert_merges,
        cfg.runtime.max_concurrent_upsert_preflights,
    ));

    info!(
        config = %cli.config.display(),
        pipelines = pipelines.len(),
        rejected = rejected.len(),
        memory_per_pipeline = ?budget.per_pipeline(),
        "config loaded"
    );
    match budget.per_pipeline() {
        Some(b) => info!(
            bytes = b,
            "each pipeline may use about {} — DataFusion spills at it, and batches are sized \
             so what they decode to fits inside it",
            bytesize::ByteSize(b)
        ),
        None => info!(
            "no memory budget: neither [runtime] max_memory nor a container limit. Nothing \
             here is bounded by size, which is fine on a workstation and worth setting in a \
             container."
        ),
    }
    let command = cli.command.unwrap_or(Command::Run);
    // `validate` still has something to say when nothing can run — that *is* its report.
    if pipelines.is_empty() && !matches!(command, Command::Validate) {
        return Err(delta_delta_ingest::Error::Config(format!(
            "nothing can run: all {} pipeline(s) were held back. See the errors above.",
            rejected.len()
        )));
    }

    match command {
        Command::Validate => {
            // The gate stays strict. Reporting every fault rather than the first is the
            // useful part — a merge request should not need three round trips to learn
            // about three typos.
            for r in &rejected {
                println!("INVALID  {:<24} {}", r.name, r.reason);
            }
            for p in &pipelines {
                // Resolving each backend touches no storage, but it does catch a URI
                // whose scheme was not compiled in and credentials that cannot assemble
                // — both of which would otherwise surface on the first batch.
                p.storage.check(&p.source_uri)?;
                p.storage.check(&p.target_uri)?;
                for lookup in &p.lookups {
                    p.storage.check(&lookup.uri)?;
                }
                // write_mode is shown because it changes what the target *is*, not just how
                // fast it fills: an upserted table holds one row per key and can only be
                // read downstream by another upserting pipeline.
                let mode = match p.upsert_key.as_deref() {
                    Some(k) if p.write_mode.is_upsert() => format!("upsert on {k}"),
                    _ => "append".to_string(),
                };
                println!(
                    "{:<24} {} -> {}  (app_id={}, change_policy={:?}, write_mode={mode})",
                    p.name, p.source_uri, p.target_uri, p.app_id, p.change_policy
                );
            }
            println!("\n{} pipeline(s) valid.", pipelines.len());
            if !rejected.is_empty() {
                // Non-zero, so a validation gate in CI actually gates.
                return Err(delta_delta_ingest::Error::Config(format!(
                    "{} pipeline(s) cannot run",
                    rejected.len()
                )));
            }
            Ok(())
        }
        Command::Status => status(pipelines, locator).await,
        Command::Once => run_all(pipelines, rejected, locator, cli.metrics_addr, true).await,
        Command::Run => run_all(pipelines, rejected, locator, cli.metrics_addr, false).await,
        Command::Dbt(_) => unreachable!("handled above, before the config is resolved"),
    }
}

/// Narrow the pipeline list to `--select`.
///
/// An unknown name is an error rather than an empty run: `ddi -s odrers` should say so,
/// not sit there looking healthy while streaming nothing.
fn select(
    pipelines: Vec<ResolvedPipeline>,
    wanted: &[String],
    rejected: &[delta_delta_ingest::config::Rejection],
) -> delta_delta_ingest::Result<Vec<ResolvedPipeline>> {
    if wanted.is_empty() {
        return Ok(pipelines);
    }
    for w in wanted {
        if !pipelines.iter().any(|p| &p.name == w) {
            // Say *why* it is not there. "matches no pipeline" for a name that is plainly in
            // the config file sends people looking for a typo that is not the problem.
            if let Some(r) = rejected.iter().find(|r| &r.name == w) {
                return Err(delta_delta_ingest::Error::Config(format!(
                    "--select {w:?} names a pipeline that was held back: {}",
                    r.reason
                )));
            }
            let mut known: Vec<&str> = pipelines.iter().map(|p| p.name.as_str()).collect();
            known.sort();
            return Err(delta_delta_ingest::Error::Config(format!(
                "--select {w:?} matches no pipeline. Known: [{}]",
                known.join(", ")
            )));
        }
    }
    Ok(pipelines
        .into_iter()
        .filter(|p| wanted.contains(&p.name))
        .collect())
}

/// The catalog of either end that is not a Delta catalog, if there is one.
fn non_delta_catalog(
    manifest: &delta_delta_ingest::dbt::Manifest,
    s: &delta_delta_ingest::dbt::analyze::Streamable,
    delta: &std::collections::BTreeSet<String>,
) -> Option<String> {
    let target = manifest.node(&s.unique_id)?;
    let source = manifest.node(&s.source_unique_id);

    std::iter::once(target.database.as_deref())
        .chain(std::iter::once(source.and_then(|n| n.database.as_deref())))
        .chain(s.lookups.iter().map(|lookup| {
            manifest
                .node(&lookup.unique_id)
                .and_then(|node| node.database.as_deref())
        }))
        .flatten()
        .find(|c| !delta.contains(*c))
        .map(str::to_string)
}

/// The first clause of a rejection, for grouping. The rest is the explanation.
fn headline(reason: &str) -> String {
    // Parser errors carry the offending token, which would make every one its own group.
    if reason.starts_with("could not parse the compiled SQL") {
        return "could not parse the compiled SQL".into();
    }
    let cut = reason
        .find(" is not supported:")
        .map(|i| i + " is not supported".len())
        .or_else(|| reason.find(';'))
        .or_else(|| reason.find(" — "))
        .unwrap_or(reason.len().min(60));
    reason[..cut.min(reason.len())].trim().to_string()
}

fn manifest_path(explicit: &Option<PathBuf>, cfg: &Config) -> delta_delta_ingest::Result<PathBuf> {
    explicit
        .clone()
        .or_else(|| cfg.manifest.as_ref().map(PathBuf::from))
        .ok_or_else(|| {
            delta_delta_ingest::Error::Config(
                "no dbt manifest: pass --manifest, or set `manifest` in the config".into(),
            )
        })
}

/// Catalogs that actually hold Delta tables, when there is a cluster to ask.
///
/// Without this, a model on an Iceberg or Hive catalog looks streamable: the SQL is
/// row-wise and the manifest says nothing about storage format. The name is no guide
/// either — `delta.x.y` may be Iceberg and `lake.x.y` may be Delta. Only the connector
/// knows, and only the cluster knows the connector.
async fn delta_catalogs(cli: &Cli) -> Option<std::collections::BTreeSet<String>> {
    let client = match build_locator(cli) {
        Ok(l) if l.is_active() => l.into_client()?,
        _ => return None,
    };
    match client.delta_catalogs().await {
        Ok(c) => {
            info!(catalogs = ?c, "catalogs backed by a Delta connector");
            Some(c)
        }
        Err(e) => {
            warn!(error = %e, "could not list catalogs; storage format will not be checked");
            None
        }
    }
}

async fn dbt_command(sub: &DbtCommand, cfg: &Config, cli: &Cli) -> delta_delta_ingest::Result<()> {
    use delta_delta_ingest::dbt::analyze::{analyze_all, Verdict};
    use delta_delta_ingest::dbt::Manifest;

    match sub {
        DbtCommand::Check {
            manifest,
            rejected_only,
        } => {
            let path = manifest_path(manifest, cfg)?;
            let m = Manifest::from_path(&path)?;
            let mut verdicts = analyze_all(&m);

            // A row-wise model on an Iceberg table is not a Delta→Delta pipeline, however
            // streamable its SQL looks.
            if let Some(delta) = delta_catalogs(cli).await {
                for v in verdicts.iter_mut() {
                    if let Verdict::Streamable(s) = v {
                        if let Some(bad) = non_delta_catalog(&m, s, &delta) {
                            *v = Verdict::Rejected {
                                name: s.name.clone(),
                                reason: format!(
                                    "catalog {bad:?} is not backed by a Delta connector, so                                      this is not a Delta→Delta pipeline"
                                ),
                            };
                        }
                    }
                }
            }

            let (mut ok, mut no, mut unknown) = (0usize, 0usize, 0usize);
            let mut why: std::collections::BTreeMap<String, usize> = Default::default();

            for v in &verdicts {
                match v {
                    Verdict::Streamable(s) => {
                        ok += 1;
                        if !rejected_only {
                            println!(
                                "streamable  {:<28} {} -> {}",
                                s.name, s.source_relation, s.target_relation
                            );
                        }
                    }
                    Verdict::Rejected { name, reason } => {
                        no += 1;
                        *why.entry(headline(reason)).or_default() += 1;
                        println!("no          {name:<28} {reason}");
                    }
                    Verdict::Unknown { name, reason } => {
                        unknown += 1;
                        *why.entry(headline(reason)).or_default() += 1;
                        println!("unknown     {name:<28} {reason}");
                    }
                }
            }

            println!(
                "\n{ok} streamable, {no} not streamable, {unknown} could not be judged, \
                 of {} model(s).",
                verdicts.len()
            );
            if unknown > 0 {
                // These are not models that cannot stream; they are models this parser
                // could not read. Counting them as rejections would understate what is
                // possible, which is a worse error than admitting the uncertainty.
                println!(
                    "\n{unknown} model(s) use SQL this parser does not accept, so nothing is \
                     claimed about them either way.\nThe streamable count is somewhere \
                     between {ok} and {}.",
                    ok + unknown
                );
            }
            if !why.is_empty() {
                let mut counts: Vec<(&String, &usize)> = why.iter().collect();
                counts.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
                println!("\nBy reason:");
                for (reason, n) in counts {
                    println!("  {n:>5}  {reason}");
                }
            }
            Ok(())
        }
        DbtCommand::Convert { manifest, out } => {
            let path = manifest_path(manifest, cfg)?;
            let m = Manifest::from_path(&path)?;
            let toml = delta_delta_ingest::dbt::convert::to_toml(&m, cfg)?;
            match out {
                Some(p) => {
                    std::fs::write(p, &toml).map_err(delta_delta_ingest::Error::Io)?;
                    println!("wrote {}", p.display());
                }
                None => print!("{toml}"),
            }
            Ok(())
        }
    }
}

/// Build the location resolver from `--target`, if one was named.
fn build_locator(cli: &Cli) -> delta_delta_ingest::Result<Locator> {
    let Some(target) = cli.target.as_deref() else {
        return Ok(Locator::none());
    };
    let path = cli.profiles_dir.as_ref().map(|d| d.join("profiles.yml"));
    let conn = delta_delta_ingest::dbt::profiles::trino_connection(
        path.as_deref(),
        cli.profile.as_deref(),
        Some(target),
    )?;
    info!(target, catalog = %conn.describe(), "resolving table locations from the catalog");
    Ok(Locator::with_client(TrinoClient::new(conn)?))
}

async fn status(
    pipelines: Vec<ResolvedPipeline>,
    locator: Arc<Locator>,
) -> delta_delta_ingest::Result<()> {
    for cfg in pipelines {
        let name = cfg.name.clone();
        let cfg = locator.refresh(&cfg).await;
        match Pipeline::open(cfg).await {
            Ok(p) => println!("{name:<24} resume_from={}", p.cursor()),
            Err(e) => println!("{name:<24} ERROR: {e}"),
        }
    }
    Ok(())
}

async fn run_all(
    pipelines: Vec<ResolvedPipeline>,
    rejected: Vec<delta_delta_ingest::config::Rejection>,
    locator: Arc<Locator>,
    metrics_addr: Option<String>,
    once: bool,
) -> delta_delta_ingest::Result<()> {
    let metrics = Metrics::new();
    let token = CancellationToken::new();

    // Held-back pipelines get a metrics entry too, reading config_valid = 0. A stream that
    // never started is otherwise invisible: it has no series at all, so a dashboard counting
    // healthy pipelines cannot tell it apart from one that was never configured.
    for r in &rejected {
        metrics
            .pipeline(&r.name)
            .config_valid
            .store(0, Ordering::Relaxed);
    }
    for p in &pipelines {
        metrics
            .pipeline(&p.name)
            .config_valid
            .store(1, Ordering::Relaxed);
    }

    if let Some(addr) = metrics_addr {
        spawn_metrics_server(addr, metrics.clone(), token.clone());
    } else if !once {
        // Worth saying out loud now that a failure is local and survivable. The process no
        // longer exits when a stream dies, so without metrics there is nothing left but
        // interleaved log lines to tell you which of them did.
        warn!(
            "no --metrics-addr: a pipeline that fails now retries instead of stopping the \
             process, so ddi_pipeline_up is the only signal that one is down. Consider \
             --metrics-addr 127.0.0.1:9100."
        );
    }

    // A JoinSet rather than a Vec of handles, so a task that ends is noticed when it ends.
    // Awaiting handles in spawn order meant a pipeline that died was invisible until every
    // pipeline before it finished — which, in `run` mode, is never.
    let mut tasks = tokio::task::JoinSet::new();
    for cfg in pipelines {
        let m = metrics.clone();
        let t = token.clone();
        let l = locator.clone();
        tasks.spawn(async move { drive(cfg, l, m, t, once).await });
    }

    // Graceful shutdown: let the in-flight step finish. A step is atomic, so stopping
    // between steps can never leave a half-applied batch.
    let shutdown = {
        let t = token.clone();
        tokio::spawn(async move {
            let _ = signal::ctrl_c().await;
            warn!("shutdown requested; finishing the current batch then stopping");
            t.cancel();
        })
    };

    let mut failed = false;
    while let Some(joined) = tasks.join_next().await {
        match joined {
            Ok(Ok(())) => {}
            Ok(Err(e)) => {
                // No `token.cancel()`. One stream's failure is not the fleet's: with
                // hundreds of them, a single malformed value used to take every healthy
                // pipeline down with it. In `run` mode a pipeline retries rather than
                // returning, so getting here at all means `--once` gave up.
                error!("pipeline failed: {e}");
                failed = true;
            }
            Err(e) => {
                // A panic is a bug rather than a data problem, and it has already unwound
                // this one task. The others keep going; the exit code reports it.
                error!("pipeline task panicked: {e}");
                failed = true;
            }
        }
    }
    shutdown.abort();

    if failed {
        return Err(delta_delta_ingest::Error::Other(
            "one or more pipelines failed".into(),
        ));
    }
    Ok(())
}

/// Holds `ddi_pipeline_up` at 1, and clears it on the way out.
///
/// A guard rather than a pair of stores because the ways out are not all returns: a panic in
/// an arrow kernel unwinds the task, and a plain `store(0)` on the error path would never
/// run. The gauge would then sit at 1 for a stream that no longer exists — the one reading
/// an operator must be able to trust.
struct Up(Arc<delta_delta_ingest::metrics::PipelineMetrics>);

impl Up {
    fn held(m: &Arc<delta_delta_ingest::metrics::PipelineMetrics>) -> Self {
        m.up.store(1, Ordering::Relaxed);
        Self(m.clone())
    }
}

impl Drop for Up {
    fn drop(&mut self) {
        self.0.up.store(0, Ordering::Relaxed);
    }
}

/// The first retry delay after a pipeline fails. Doubles from here.
const RETRY_MIN: Duration = Duration::from_secs(1);
/// The ceiling on that doubling.
///
/// Generous on purpose. Reopening a pipeline is not free — it rereads the target to find its
/// watermark — so a stream stuck on something only a human can fix must not spend the whole
/// interval between fixes rescanning. Five minutes keeps that affordable while still
/// recovering on its own within one poll of somebody repairing the cause. Nothing is lost by
/// waiting, because the backoff resets the moment a step succeeds.
const RETRY_MAX: Duration = Duration::from_secs(300);

/// One tokio task per pipeline, supervised. No coordination between them: masterless,
/// like KDI.
///
/// # Why this retries rather than returning
///
/// A pipeline used to return its first error, which ended the task for good — and the join
/// loop then cancelled every other pipeline. At one pipeline that reads as "stop the world
/// and let a human look". At three hundred it reads as "any one stream can take down the
/// other two hundred and ninety-nine", which is not a trade anybody would choose.
///
/// So a failure is now local and temporary: this pipeline backs off and tries again, its
/// peers never notice, and `ddi_pipeline_up` says which of them are healthy. Nothing is
/// swallowed — the error is logged every time and `ddi_errors_total` counts it — but the
/// process keeps serving the streams that are fine.
///
/// Retrying is safe for the same reason a crash is: a step is atomic, so a failed one
/// changed nothing and simply happens again.
async fn drive(
    cfg: ResolvedPipeline,
    locator: Arc<Locator>,
    metrics: Metrics,
    token: CancellationToken,
    once: bool,
) -> delta_delta_ingest::Result<()> {
    let name = cfg.name.clone();
    let m = metrics.pipeline(&name);
    let mut backoff = RETRY_MIN;
    let mut attempts = 0u32;

    loop {
        let progressed = Arc::new(std::sync::atomic::AtomicBool::new(false));
        let outcome = attempt(&cfg, &locator, &m, &token, once, &progressed).await;

        // Any successful step means the cause cleared, so the next failure starts over at a
        // second rather than inheriting five minutes of penalty from an outage last week.
        if progressed.load(Ordering::Relaxed) {
            backoff = RETRY_MIN;
            attempts = 0;
        }

        match outcome {
            Ok(()) => return Ok(()),
            Err(e) => {
                m.errors.fetch_add(1, Ordering::Relaxed);
                m.up.store(0, Ordering::Relaxed);

                // `--once` is a batch run: something is waiting on the exit code, so
                // retrying forever would hang it. Report and let run_all sum up.
                if once {
                    error!(pipeline = %name, "{e}");
                    return Err(e);
                }
                if token.is_cancelled() {
                    return Ok(());
                }

                attempts += 1;
                let wait = jitter(backoff, &name, attempts);
                error!(
                    pipeline = %name,
                    retry_in_ms = wait.as_millis() as u64,
                    attempt = attempts,
                    "pipeline failed; retrying. Other pipelines are unaffected. {e}"
                );
                m.restarts.fetch_add(1, Ordering::Relaxed);
                sleep_or_cancel(wait, &token).await;
                if token.is_cancelled() {
                    // Otherwise shutdown pays for one more full reopen, per pipeline.
                    return Ok(());
                }
                backoff = RETRY_MAX.min(backoff * 2);
            }
        }
    }
}

/// Sleep, but wake immediately on shutdown rather than making Ctrl-C wait out a backoff.
async fn sleep_or_cancel(total: Duration, token: &CancellationToken) {
    const TICK: Duration = Duration::from_millis(200);
    let mut left = total;
    while left > Duration::ZERO && !token.is_cancelled() {
        let step = TICK.min(left);
        tokio::time::sleep(step).await;
        left -= step;
    }
}

/// Spread a retry by up to ±25%.
///
/// Three hundred pipelines knocked over by one object-store outage must not come back in
/// lockstep and cause the next one — each reopen rereads a target. Derived from the name
/// *and the attempt number* rather than an RNG: no dependency, reproducible, and varying per
/// attempt so two pipelines that happen to hash alike drift apart instead of staying
/// phase-locked forever.
fn jitter(d: Duration, name: &str, attempt: u32) -> Duration {
    let seed = name.bytes().fold(attempt as u64, |a, b| {
        a.wrapping_mul(31).wrapping_add(b as u64)
    });
    // 0..=50, so the factor runs from 0.75 to 1.25.
    let factor = 75 + seed % 51;
    Duration::from_millis((d.as_millis() as u64).saturating_mul(factor) / 100)
}

/// Open the pipeline and run it until it is done, cancelled, or fails.
///
/// Sets `progressed` on the first successful step, which is what tells the supervisor the
/// cause cleared and the backoff may reset.
async fn attempt(
    cfg: &ResolvedPipeline,
    locator: &Arc<Locator>,
    m: &Arc<delta_delta_ingest::metrics::PipelineMetrics>,
    token: &CancellationToken,
    once: bool,
    progressed: &Arc<std::sync::atomic::AtomicBool>,
) -> delta_delta_ingest::Result<()> {
    let name = cfg.name.clone();
    let idle = Duration::from_secs(cfg.allowed_latency_secs.max(1));

    if token.is_cancelled() {
        return Ok(());
    }
    let mut current = locator.refresh(cfg).await;
    let mut pipeline = Pipeline::open(current.clone()).await?;
    // Cleared on the way out however this returns — including an unwind — so a panicked
    // task cannot leave the fleet's health gauge claiming it is fine.
    let _up = Up::held(m);

    loop {
        if token.is_cancelled() {
            info!(pipeline = %name, "stopped");
            return Ok(());
        }

        // Ask the catalog where these tables are now. A relocation is invisible in
        // storage — the old table just goes quiet — so the only way to notice is to keep
        // asking. Reopening is safe: a different location is a different table, and the
        // pipeline's own identity check restarts it with the dedup filter suppressing
        // whatever the target already holds.
        let fresh = locator.refresh(&current).await;
        if locate::moved(&current, &fresh) {
            warn!(
                pipeline = %name,
                source = %fresh.source_uri,
                target = %fresh.target_uri,
                "table location changed; reopening"
            );
            current = fresh;
            pipeline = Pipeline::open(current.clone()).await?;
        }

        let outcome = pipeline.step().await;

        // Record head and cursor on every step, including CaughtUp — otherwise the lag
        // gauge freezes at whatever it was when the last batch committed instead of
        // falling to zero once the pipeline has drained the source.
        if let Some(head) = pipeline.source_head_version() {
            m.source_head_version.store(head as i64, Ordering::Relaxed);
        }
        m.cursor_version
            .store(pipeline.cursor().version as i64, Ordering::Relaxed);

        match outcome {
            Ok(StepOutcome::CaughtUp) => {
                progressed.store(true, Ordering::Relaxed);
                m.mark_progress();
                if once {
                    info!(pipeline = %name, "caught up");
                    return Ok(());
                }
                tokio::time::sleep(idle).await;
            }
            Ok(StepOutcome::Progressed {
                through_version,
                files,
                rows,
                upsert,
                rejected,
                ..
            }) => {
                // A step that got this far means the pipeline is working, whatever happened
                // before it. Clearing `up` here rather than only on open makes the gauge
                // track reality during a flapping outage.
                progressed.store(true, Ordering::Relaxed);
                m.mark_progress();
                m.rows_rejected
                    .fetch_add(rejected as u64, Ordering::Relaxed);
                if rejected > 0 && rows == 0 {
                    m.batches_fully_rejected.fetch_add(1, Ordering::Relaxed);
                }
                m.batches_committed.fetch_add(1, Ordering::Relaxed);
                m.rows_written.fetch_add(rows as u64, Ordering::Relaxed);
                m.files_read.fetch_add(files as u64, Ordering::Relaxed);
                m.last_source_version
                    .store(through_version as i64, Ordering::Relaxed);
                if let Some(u) = upsert {
                    m.rows_updated
                        .fetch_add(u.updated as u64, Ordering::Relaxed);
                    m.rows_inserted
                        .fetch_add(u.inserted as u64, Ordering::Relaxed);
                    m.target_files_scanned
                        .fetch_add(u.files_scanned as u64, Ordering::Relaxed);
                    if !u.window_bounded {
                        m.upsert_window_unbounded.fetch_add(1, Ordering::Relaxed);
                    }
                    if u.window_clamped {
                        m.upsert_window_clamped.fetch_add(1, Ordering::Relaxed);
                    }
                    m.merges.fetch_add(1, Ordering::Relaxed);
                    m.merge_millis.fetch_add(u.merge_millis, Ordering::Relaxed);
                    m.merge_queue_millis
                        .fetch_add(u.queue_millis, Ordering::Relaxed);
                }
            }
            Ok(StepOutcome::Skipped {
                through_version,
                rejected,
            }) => {
                progressed.store(true, Ordering::Relaxed);
                m.mark_progress();
                m.rows_rejected
                    .fetch_add(rejected as u64, Ordering::Relaxed);
                if rejected > 0 {
                    // Nothing reached the target and everything was rejected — the shape an
                    // upstream type change takes. Counted separately because the target
                    // simply stops growing, which no other metric would show.
                    m.batches_fully_rejected.fetch_add(1, Ordering::Relaxed);
                }
                m.commits_skipped.fetch_add(1, Ordering::Relaxed);
                m.last_source_version
                    .store(through_version as i64, Ordering::Relaxed);
            }
            Err(e) => {
                // Hand it to the supervisor above, which backs off and reopens. Not counted
                // here: `drive` does that once, so a retry is one error, not two.
                return Err(e);
            }
        }
    }
}

fn spawn_metrics_server(addr: String, metrics: Metrics, token: CancellationToken) {
    tokio::spawn(async move {
        let listener = match tokio::net::TcpListener::bind(&addr).await {
            Ok(l) => l,
            Err(e) => {
                error!("metrics: cannot bind {addr}: {e}");
                return;
            }
        };
        info!(%addr, "metrics listening on /metrics");
        loop {
            if token.is_cancelled() {
                return;
            }
            let Ok((mut sock, _)) = listener.accept().await else {
                continue;
            };
            let body = metrics.render();
            let resp = format!(
                "HTTP/1.1 200 OK\r\nContent-Type: text/plain; version=0.0.4\r\n\
                 Content-Length: {}\r\nConnection: close\r\n\r\n{body}",
                body.len()
            );
            use tokio::io::AsyncWriteExt;
            let _ = sock.write_all(resp.as_bytes()).await;
            let _ = sock.shutdown().await;
        }
    });
}
